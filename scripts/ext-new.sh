#!/bin/sh
# Generate an extension crate in pkgs/extensions and register it (Cargo members,
# Makefile GUESTS), so `make extensions` builds it.
#
# Usage: scripts/ext-new.sh <name> <kind>
#   kind ∈ provider | tool | interceptor | registry-skills | registry-mcp
#
# Shell, not an xtask: the per-kind difference is one world line and one trait
# impl, which sed substitutes. Revisit if the per-kind table grows logic.
# Stubs return real values, not todo!(), so the first build passes.
set -eu

NAME="${1:-}"
KIND="${2:-}"
# Rust unless asked otherwise: every first-party extension is Rust.
LANG="${3:-rust}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
# Overridable so the self-test generates into a scratch directory.
EXT="${EXT_ROOT:-$ROOT/pkgs/extensions}"

usage() {
    echo "usage: ext-new.sh <name> <kind> [lang]" >&2
    echo "  kind ∈ provider | tool | interceptor | registry-skills | registry-mcp" >&2
    echo "  lang ∈ rust (default) | ts | py" >&2
    exit 2
}

[ -n "$NAME" ] && [ -n "$KIND" ] || usage
case "$NAME" in
    *[!a-z0-9-]* | "" | -* ) echo "ext-new: name must be lowercase letters, digits and dashes: $NAME" >&2; exit 2 ;;
esac
[ -e "$EXT/$NAME" ] && { echo "ext-new: $EXT/$NAME already exists" >&2; exit 2; }

# The per-kind table: the only difference between kinds.
case "$KIND" in
    provider)
        WORLD="provider-world";       IFACE="llm_provider";   TRAIT="LlmProvider"
        TYPES="CompletionChunk, CompletionRequest, ProviderError, ProviderInfo, StreamHandle" ;;
    tool)
        WORLD="tool-world";           IFACE="tool_callable";  TRAIT="ToolCallable"
        TYPES="ToolError, ToolMeta" ;;
    interceptor)
        WORLD="interceptor-world";    IFACE="interceptor";    TRAIT="Interceptor"
        TYPES="Decision, InterceptInput, InterceptorError, Phase" ;;
    registry-skills)
        WORLD="skill-registry-world"; IFACE="skill_registry"; TRAIT="SkillRegistry"
        TYPES="SkillError, SkillInfo" ;;
    registry-mcp)
        WORLD="mcp-registry-world";   IFACE="mcp_registry";   TRAIT="McpRegistry"
        TYPES="McpError, ServerInfo, ToolInfo" ;;
    *) echo "ext-new: unknown kind: $KIND" >&2; usage ;;
esac


# Description is the same placeholder the manifest carries; the author replaces both.
write_readme() {
    cat > "$EXT/$NAME/README.md" <<EOF
# $NAME

A $KIND extension. Replace this description with what it does.

A \`$KIND\` extension: a WebAssembly component built against [\`wit/\`](../../../wit).

\`\`\`sh
$1
\`\`\`

The capabilities it needs are read from the built component into \`ext/$NAME.manifest.toml\`; they are not listed here.
EOF
}

# TypeScript: no Cargo.toml or generated bindings; registers in TS_GUESTS. jco
# lowers kebab-case to lowerCamelCase, and componentize checks the shapes below.
# Only tool and interceptor: a template nobody writes would be kept correct for free.
if [ "$LANG" = "ts" ]; then
    case "$KIND" in
        tool|interceptor) ;;
        *)
            echo "ext-new: LANG=ts has no template for kind '$KIND'" >&2
            echo "  supported: tool | interceptor — add a stub to ext-new.sh for others" >&2
            exit 2 ;;
    esac

    mkdir -p "$EXT/$NAME/src"

    cat > "$EXT/$NAME/package.json" <<EOF
{
  "name": "$NAME",
  "version": "0.1.0",
  "private": true,
  "description": "A $KIND extension in TypeScript. Replace this description with what it does.",
  "type": "module"
}
EOF

    cat > "$EXT/$NAME/src/guest.ts" <<EOF
/**
 * \`$NAME\` — a $KIND extension in TypeScript.
 *
 * Generated by \`make ext-new NAME=$NAME KIND=$KIND LANG=ts\`. Replace the stubs
 * below; they return real values rather than throwing, so this componentizes
 * and runs from the first build.
 *
 * Built by \`make -C pkgs/extensions ts-guest\`, which needs \`jco\` on PATH and
 * skips where it is absent. The component carries a JavaScript engine, so it
 * is ~12.7 MB against a Rust guest's ~55 KB — the price of the language, not
 * of this extension.
 */

/** The world's \`extension-lifecycle\` export. */
export const extensionLifecycle = {
  init(_context: { id: string; version: string }): void {},
  start(): void {},
  stop(): void {},
  /** \`health-status\` is an enum; jco lowers its cases to strings. */
  health(): string {
    return "up";
  },
};
EOF

    # Appended, not captured in $( ): an apostrophe in a heredoc there breaks parsing.
    if [ "$KIND" = "tool" ]; then
        cat >> "$EXT/$NAME/src/guest.ts" <<'EOF'

/** The world's `tool-callable` export. */
export const toolCallable = {
  meta() {
    return {
      name: "NAME_PLACEHOLDER",
      description: "Describe what this tool does — the model reads this.",
      // JSON Schema for `invoke`'s argument string.
      argumentsSchema: JSON.stringify({ type: "object", properties: {} }),
    };
  },

  /** `arguments` is a JSON string and so is the result; the interface says so. */
  invoke(_args: string): string {
    return "replace me";
  },
};
EOF
    else
        cat >> "$EXT/$NAME/src/guest.ts" <<'EOF'

/** The world's `interceptor` export. */
export const interceptor = {
  /**
   * `proceed` changes nothing, which is the right default: an interceptor that
   * has not decided anything must not alter the turn.
   */
  intercept(_input: unknown): { tag: string } {
    return { tag: "proceed" };
  },

  /**
   * Nothing yet. Subscribe only to the phases you act on — the host calls you
   * for every one you name.
   */
  subscribedPhases(): string[] {
    return [];
  },
};
EOF
    fi

    # Quoted heredocs, so substitute after writing; sed -i is not portable.
    sed "s/NAME_PLACEHOLDER/$NAME/g" "$EXT/$NAME/src/guest.ts" > "$EXT/$NAME/src/guest.ts.tmp" \
        && mv "$EXT/$NAME/src/guest.ts.tmp" "$EXT/$NAME/src/guest.ts"

    # Idempotent: re-registering would build and stage the guest twice.
    if [ -f "$EXT/Makefile" ] && ! grep -q "TS_GUESTS :=.*[ =]$NAME\( \|$\)" "$EXT/Makefile"; then
        awk -v name="$NAME" '
            /^TS_GUESTS :=/ && !done { print $0 " " name; done = 1; next }
            { print }
        ' "$EXT/Makefile" > "$EXT/Makefile.tmp" && mv "$EXT/Makefile.tmp" "$EXT/Makefile"
    fi

    write_readme "make -C pkgs/extensions ts-guest"
    echo "ext-new: wrote $EXT/$NAME ($KIND, $WORLD, TypeScript)"
    echo "ext-new: registered in TS_GUESTS"
    echo "ext-new: next — \`make -C pkgs/extensions ts-guest\` builds it (needs jco)"
    exit 0
fi

# Python: componentize-py generates a wit_world package, so the stubs are checked
# against the WIT. That package is build output (gitignored, regenerated by
# `make -C pkgs/extensions py-guest`), not scaffolding.
# componentize-py lowers kebab-case to snake_case (Decision_Proceed for a variant case).
if [ "$LANG" = "py" ]; then
    case "$KIND" in
        tool|interceptor) ;;
        *)
            echo "ext-new: LANG=py has no template for kind '$KIND'" >&2
            echo "  supported: tool | interceptor — add a stub to ext-new.sh for others" >&2
            exit 2 ;;
    esac

    mkdir -p "$EXT/$NAME"

    cat > "$EXT/$NAME/pyproject.toml" <<EOF
# Read by scripts/manifests.sh for the generated manifest's version and
# description, the way a Rust guest's Cargo.toml and a TypeScript guest's
# package.json are. Not installed and not published — componentize-py takes
# the module directly.
[project]
name = "$NAME"
version = "0.1.0"
description = "A $KIND extension in Python. Replace this description with what it does."
requires-python = ">=3.11"
EOF

    cat > "$EXT/$NAME/app.py" <<EOF
"""\`$NAME\` — a $KIND extension in Python.

Generated by \`make ext-new NAME=$NAME KIND=$KIND LANG=py\`. Replace the stubs
below; they return real values rather than raising, so this componentizes and
runs from the first build.

Built by \`make -C pkgs/extensions py-guest\`, which needs \`componentize-py\` on
PATH and skips where it is absent. The component carries CPython, so it is
~18.5 MB against a Rust guest's ~55 KB — the price of the language, not of
this extension.

The \`wit_world\` package imported below is generated by the build from
\`wit/\`. It is not committed: run the build once before your editor will
resolve these imports.
"""

EOF

    # Appended, not captured (see the TypeScript block).
    if [ "$KIND" = "tool" ]; then
        cat >> "$EXT/$NAME/app.py" <<'EOF'
import json

import wit_world
from wit_world.exports import ExtensionLifecycle as ExtensionLifecycleProtocol
from wit_world.exports import ToolCallable as ToolCallableProtocol
from wit_world.exports.extension_lifecycle import ExtensionContext, HealthStatus
from wit_world.exports.tool_callable import ToolMeta


class WitWorld(wit_world.WitWorld):
    """The world itself exports nothing beyond its interfaces."""


class ExtensionLifecycle(ExtensionLifecycleProtocol):
    def init(self, ctx: ExtensionContext) -> None:
        pass

    def start(self) -> None:
        pass

    def stop(self) -> None:
        pass

    def health(self) -> HealthStatus:
        return HealthStatus.UP


class ToolCallable(ToolCallableProtocol):
    def meta(self) -> ToolMeta:
        return ToolMeta(
            name="NAME_PLACEHOLDER",
            description="Describe what this tool does — the model reads this.",
            # JSON Schema for the argument string `invoke` receives.
            arguments_schema=json.dumps({"type": "object", "properties": {}}),
        )

    def invoke(self, arguments: str) -> str:
        """`arguments` is a JSON string and so is the result."""
        return json.dumps({"result": "replace me"})
EOF
    else
        cat >> "$EXT/$NAME/app.py" <<'EOF'
from typing import List

import wit_world
from wit_world.exports import ExtensionLifecycle as ExtensionLifecycleProtocol
from wit_world.exports import Interceptor as InterceptorProtocol
from wit_world.exports.extension_lifecycle import ExtensionContext, HealthStatus
from wit_world.exports.interceptor import (
    Decision,
    Decision_Proceed,
    InterceptInput,
    Phase,
)


class WitWorld(wit_world.WitWorld):
    """The world itself exports nothing beyond its interfaces."""


class ExtensionLifecycle(ExtensionLifecycleProtocol):
    def init(self, ctx: ExtensionContext) -> None:
        pass

    def start(self) -> None:
        pass

    def stop(self) -> None:
        pass

    def health(self) -> HealthStatus:
        return HealthStatus.UP


class Interceptor(InterceptorProtocol):
    def intercept(self, input: InterceptInput) -> Decision:
        """`proceed` changes nothing, which is the right default: an
        interceptor that has not decided anything must not alter the turn.
        """
        return Decision_Proceed()

    def subscribed_phases(self) -> List[Phase]:
        """Nothing yet. Subscribe only to the phases you act on — the host
        calls you for every one you name.
        """
        return []
EOF
    fi

    sed "s/NAME_PLACEHOLDER/$NAME/g" "$EXT/$NAME/app.py" > "$EXT/$NAME/app.py.tmp" \
        && mv "$EXT/$NAME/app.py.tmp" "$EXT/$NAME/app.py"

    if [ -f "$EXT/Makefile" ] && ! grep -q "PY_GUESTS :=.*[ =]$NAME\( \|$\)" "$EXT/Makefile"; then
        awk -v name="$NAME" '
            /^PY_GUESTS :=/ && !done { print $0 " " name; done = 1; next }
            { print }
        ' "$EXT/Makefile" > "$EXT/Makefile.tmp" && mv "$EXT/Makefile.tmp" "$EXT/Makefile"
    fi

    write_readme "make -C pkgs/extensions py-guest"
    echo "ext-new: wrote $EXT/$NAME ($KIND, $WORLD, Python)"
    echo "ext-new: registered in PY_GUESTS"
    echo "ext-new: next — \`make -C pkgs/extensions py-guest\` builds it (needs componentize-py)"
    exit 0
fi

mkdir -p "$EXT/$NAME/src"

cat > "$EXT/$NAME/Cargo.toml" <<EOF
[package]
name = "$NAME"
version = "0.1.0"
edition.workspace = true
license.workspace = true
publish.workspace = true
description = "A $KIND extension. Replace this description with what it does."

[lib]
crate-type = ["cdylib"]

[dependencies]
wit-bindgen.workspace = true

[lints]
workspace = true
EOF

stub_tool() {
    cat <<'EOF'
    impl ToolCallable for Component {
        fn meta() -> ToolMeta {
            ToolMeta {
                name: "NAME_PLACEHOLDER".to_string(),
                description: "Describe what this tool does — the model reads this.".to_string(),
                // JSON Schema for `invoke`'s argument string.
                arguments_schema: r#"{"type":"object","properties":{}}"#.to_string(),
            }
        }

        fn invoke(_arguments: String) -> Result<String, ToolError> {
            Ok("replace me".to_string())
        }
    }
EOF
}

stub_provider() {
    cat <<'EOF'
    impl LlmProvider for Component {
        fn complete(_request: CompletionRequest) -> Result<StreamHandle, ProviderError> {
            Err(ProviderError::Unreachable)
        }

        fn next_chunk(_handle: StreamHandle) -> Option<CompletionChunk> {
            None
        }

        fn close_stream(_handle: StreamHandle) {}

        fn info() -> ProviderInfo {
            ProviderInfo {
                id: "NAME_PLACEHOLDER".to_string(),
                supported_models: Vec::new(),
            }
        }
    }
EOF
}

stub_interceptor() {
    cat <<'EOF'
    impl Interceptor for Component {
        fn intercept(_input: InterceptInput) -> Result<Decision, InterceptorError> {
            // `Proceed` changes nothing, which is the right default: an
            // interceptor that has not decided anything must not alter the turn.
            Ok(Decision::Proceed)
        }

        fn subscribed_phases() -> Vec<Phase> {
            // Nothing yet. Subscribe only to the phases you act on — the host
            // calls you for every one you name.
            Vec::new()
        }
    }
EOF
}

stub_registry_skills() {
    cat <<'EOF'
    impl SkillRegistry for Component {
        fn list_skills() -> Result<Vec<SkillInfo>, SkillError> {
            Ok(Vec::new())
        }

        fn get_skill(_name: String) -> Result<SkillInfo, SkillError> {
            Err(SkillError::NotFound)
        }

        fn invoke(_name: String, _arguments: String) -> Result<String, SkillError> {
            Err(SkillError::NotFound)
        }

        fn reload() -> Result<(), SkillError> {
            Ok(())
        }
    }
EOF
}

stub_registry_mcp() {
    cat <<'EOF'
    impl McpRegistry for Component {
        fn list_servers() -> Result<Vec<ServerInfo>, McpError> {
            Ok(Vec::new())
        }

        fn list_tools() -> Result<Vec<ToolInfo>, McpError> {
            Ok(Vec::new())
        }

        fn invoke_tool(_name: String, _arguments: String) -> Result<String, McpError> {
            Err(McpError::ToolNotFound)
        }

        fn reconnect(_server_id: String) -> Result<(), McpError> {
            Err(McpError::ServerNotFound)
        }
    }
EOF
}

case "$KIND" in
    provider)        STUB="$(stub_provider)" ;;
    tool)            STUB="$(stub_tool)" ;;
    interceptor)     STUB="$(stub_interceptor)" ;;
    registry-skills) STUB="$(stub_registry_skills)" ;;
    registry-mcp)    STUB="$(stub_registry_mcp)" ;;
esac
STUB="$(printf '%s' "$STUB" | sed "s/NAME_PLACEHOLDER/$NAME/g")"

cat > "$EXT/$NAME/src/lib.rs" <<EOF
//! \`$NAME\` — a $KIND extension.
//!
//! Generated by \`make ext-new NAME=$NAME KIND=$KIND\`. Replace the stubs below;
//! they return real values rather than \`todo!()\` so this compiles from the
//! first build.
//!
//! Component-Model glue only, so it compiles for \`wasm32\` only.

#[cfg(target_arch = "wasm32")]
mod component {
    #[allow(
        unsafe_code,
        missing_docs,
        clippy::all,
        clippy::pedantic,
        clippy::nursery
    )]
    mod bindings {
        wit_bindgen::generate!({
            world: "$WORLD",
            path: "../../../wit",
        });
    }

    use bindings::exports::jan_klod::interfaces::extension_lifecycle::{
        ExtensionContext, Guest as Lifecycle, HealthStatus,
    };
    // Named, not a glob. \`clippy::wildcard-imports\` is denied workspace-wide,
    // so a \`::*\` here would make the generated crate fail the repository's own
    // lints before its author had written a line — and the trait is aliased
    // because wit-bindgen calls every exported interface's trait \`Guest\`,
    // including the lifecycle one above.
    use bindings::exports::jan_klod::interfaces::$IFACE::{Guest as $TRAIT, $TYPES};
    use bindings::jan_klod::interfaces::host_log::{self, LogLevel};

    fn log(level: LogLevel, message: &str) {
        host_log::log(level, "$NAME", message, &[]);
    }

    struct Component;

    impl Lifecycle for Component {
        fn init(ctx: ExtensionContext) -> Result<(), String> {
            log(
                LogLevel::Info,
                &format!("init id={} version={}", ctx.id, ctx.version),
            );
            Ok(())
        }
        fn start() -> Result<(), String> {
            Ok(())
        }
        fn stop() {}
        fn health() -> HealthStatus {
            HealthStatus::Up
        }
    }

$STUB

    #[allow(
        unsafe_code,
        missing_docs,
        clippy::all,
        clippy::pedantic,
        clippy::nursery
    )]
    mod glue {
        use super::{bindings, Component};
        bindings::export!(Component with_types_in bindings);
    }
}
EOF

# Idempotent: re-registering would build and stage the guest twice. Skipped
# without a workspace, which is how the self-test generates into a scratch directory.
if [ -f "$EXT/Cargo.toml" ] && ! grep -q "^    \"$NAME\"," "$EXT/Cargo.toml"; then
    awk -v name="$NAME" '
        /^]/ && !done { print "    \"" name "\","; done = 1 }
        { print }
    ' "$EXT/Cargo.toml" > "$EXT/Cargo.toml.tmp" && mv "$EXT/Cargo.toml.tmp" "$EXT/Cargo.toml"
fi

if [ -f "$EXT/Makefile" ] && ! grep -q "GUESTS :=.*[ =]$NAME\( \|$\)" "$EXT/Makefile"; then
    awk -v name="$NAME" '
        /^GUESTS :=/ && !done { print $0 " " name; done = 1; next }
        { print }
    ' "$EXT/Makefile" > "$EXT/Makefile.tmp" && mv "$EXT/Makefile.tmp" "$EXT/Makefile"
fi

# Format after registration (`-p` needs a workspace member): the import line length
# varies by kind, so no fixed layout passes fmt --check.
if [ -f "$EXT/Cargo.toml" ]; then
    cargo fmt --manifest-path "$EXT/Cargo.toml" -p "$NAME"
else
    # No workspace: format the file directly, so scratch output compares byte-for-byte.
    rustfmt --edition 2021 "$EXT/$NAME/src/lib.rs"
fi

write_readme "make -C pkgs/extensions all   # builds every guest and stages ext/$NAME.wasm with its manifest"
echo "ext-new: wrote $EXT/$NAME ($KIND, $WORLD)"
echo "ext-new: registered in the extensions workspace and GUESTS"
echo "ext-new: next — \`make extensions\` builds it and generates its manifest"
