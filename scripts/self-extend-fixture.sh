#!/bin/sh
# Prepare the crate the end-to-end self-extension test compiles.
#
# The test builds a real component inside self-extend's jail, which denies the
# network. Two things must exist first, and only an online run outside the jail
# can provide them: a lock file (offline resolution of an unfetched crate fails),
# and fetched crates (extraction writes under CARGO_HOME, outside the jail's
# writable workspace). The build below does both; the jailed build then needs no network.
#
# Not `cargo vendor`: a lock plus the shared cargo cache is about 1 MB, against
# 34 MB for vendoring, and needs no config redirect.
#
# target/ is removed at the end: 168 MB that nothing reads.
set -eu

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DIR="${1:-$ROOT/.fixtures/self-extend-guest}"

mkdir -p "$DIR/src" "$DIR/wit"
# All of wit/: generate! parses every file in the directory.
cp "$ROOT"/wit/*.wit "$DIR/wit/"

cat > "$DIR/Cargo.toml" <<'MANIFEST'
# Generated by scripts/self-extend-fixture.sh — regenerate, do not edit.
[package]
name = "self-built"
version = "0.0.0"
edition = "2021"

[lib]
crate-type = ["cdylib"]

[dependencies]
wit-bindgen = "0.46"

# Debug info is most of what a wasm guest build writes: 385 MB with it, 168 MB
# without, and nothing debugs this. Disk is the constraint, not build time.
[profile.dev]
debug = false
strip = "debuginfo"
incremental = false

[workspace]
MANIFEST

cat > "$DIR/src/lib.rs" <<'SOURCE'
// Generated by scripts/self-extend-fixture.sh — regenerate, do not edit.
//
// Stands in for what an agent writes: the smallest component that is a real
// tool. It imports nothing, so the manifest that has to accompany it declares
// nothing, which keeps the chain test about the *chain* rather than about
// capability declaration.
#[allow(unsafe_code, missing_docs, clippy::all, clippy::pedantic, clippy::nursery)]
mod bindings {
    wit_bindgen::generate!({
        world: "tool-world",
        path: "wit",
    });
}

use bindings::exports::jan_klod::interfaces::extension_lifecycle::{
    ExtensionContext, Guest as Lifecycle, HealthStatus,
};
use bindings::exports::jan_klod::interfaces::tool_callable::{
    Guest as ToolCallable, ToolError, ToolMeta,
};

struct Component;

impl Lifecycle for Component {
    fn init(_ctx: ExtensionContext) -> Result<(), String> {
        Ok(())
    }
    fn start() -> Result<(), String> {
        Ok(())
    }
    fn stop() {}
    fn health() -> HealthStatus {
        HealthStatus::Up
    }
}

impl ToolCallable for Component {
    fn meta() -> ToolMeta {
        ToolMeta {
            name: "self-built".to_string(),
            description: "Answers with a phrase only this component knows.".to_string(),
            arguments_schema: r#"{"type":"object","properties":{}}"#.to_string(),
        }
    }

    // The phrase is what the chain test asserts on: it can only reach the
    // model if this component was compiled, installed, adopted and called.
    fn invoke(_arguments: String) -> Result<String, ToolError> {
        Ok("compiled-in-session".to_string())
    }
}

#[allow(unsafe_code, missing_docs, clippy::all, clippy::pedantic, clippy::nursery)]
mod glue {
    use super::{bindings, Component};
    bindings::export!(Component with_types_in bindings);
}
SOURCE

cd "$DIR"
# Online: resolve and fetch, writing Cargo.lock.
cargo fetch --target wasm32-wasip2
# Offline build: extracts the sources and proves the fixture compiles.
cargo build --offline --locked --target wasm32-wasip2
test -f target/wasm32-wasip2/debug/self_built.wasm || {
    echo "self-extend-fixture: the fixture did not build" >&2
    exit 1
}
rm -rf target

echo "self-extend-fixture: ready in $DIR"
echo "  the chain test compiles this inside the jail; nothing here is committed"
